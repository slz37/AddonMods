local MEDIA_KEYS = {
	font	  = 'Fonts',
	sound	  = 'Sounds',
	arrow	  = 'Arrows',
	mail	  = 'MailIcons',
	resting = 'RestIcons',
	emoji	  = 'ChatEmojis',
	logo	  = 'ChatLogos',
	texture	= 'Textures',
}

---@param type string
---@param file string
---@param name string?
---@param customType string|table<string, any>?
---@param mask number?
local function addMedia(type, file, name, customType, mask)
	local path = MEDIA_PATHS[type]
	if path then
		local key      = file:gsub('%.%w-$','')
		local filePath = path .. file

		local pathKey = MEDIA_KEYS[type]
		if pathKey then addonMods.media[pathKey][key] = filePath end

		if name then -- Register to LSM
			local nameKey = (name == true and key) or name
			if type(customType) == 'table' then
				for _, customName in ipairs(customType) do
					LSM:Register(customName, nameKey, filePath, mask)
				end
			else
				LSM:Register(customType or type, nameKey, filePath, mask)
			end
		end
	end
end

