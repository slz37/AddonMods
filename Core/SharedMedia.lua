local MEDIA_PATHS = {
	font	    = [[Interface\AddOns\AddonMods\Media\Fonts\]],
	sound	    = [[Interface\AddOns\AddonMods\Media\Sounds\]],
	arrow	    = [[Interface\AddOns\AddonMods\Media\Arrows\]],
